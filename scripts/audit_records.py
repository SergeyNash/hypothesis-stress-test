#!/usr/bin/env python3
"""Initialize audit outputs and register typed records bound to captured source text."""
import time as _hst_clock
_HST_STARTED = _hst_clock.perf_counter()
_HST_CPU_STARTED = _hst_clock.process_time()
import argparse
import json
from pathlib import Path
import re
from run_progress import atomic, output_dir, lock
from run_quality import KINDS, normalized
from runtime_metrics import timed

ROOT=Path(__file__).resolve().parents[1]


def initialize(run):
    output=output_dir(run)
    defaults={'source_snapshot.json':{'schema_version':1,'files':[],'captures':[]},
              'claim_ledger.json':{'sources':[],'claims':[]},
              'quality_review.json':json.loads((ROOT/'templates/quality_review.json').read_text(encoding='utf-8'))}
    for name,value in defaults.items():
        if not (output/name).exists():atomic(output/name,json.dumps(value,ensure_ascii=False,indent=2))


def _put(run,kind,record,*,ledger=None,commit=True):
    from source_selection import require
    run=Path(run).resolve();output=output_dir(run)
    if ledger is None:ledger=json.loads((output/'claim_ledger.json').read_text(encoding='utf-8-sig'))
    item=dict(record);inventory=item.pop('inventory',None)
    if not isinstance(item.get('id'),str):raise ValueError('Record requires id')
    if kind=='source':
        if item.get('kind') not in KINDS or not item.get('independence_group') or not item.get('scopes'):
            raise ValueError('Use a valid source kind, independence_group and scopes')
        if not isinstance(item.get('facts',[]),list) or any(not isinstance(f,dict) for f in item.get('facts',[])):
            raise ValueError('Source facts must be structured objects, never summary strings')
        if item['kind']=='simulation':
            if item.get('role')!='simulation':raise ValueError('Simulation requires role=simulation')
            files=[]
        else:
            snapshot=json.loads((output/'source_snapshot.json').read_text(encoding='utf-8-sig'))
            anchors={u['anchor_id']:(f,u) for f in snapshot['files'] for u in f['units']}
            ids=item.get('anchor_ids',[]);quote=item.get('quote','')
            if not ids or any(i not in anchors for i in ids):raise ValueError('Use anchor IDs generated by source_snapshot.py')
            if not quote or '\n' in quote or not any(normalized(quote) in normalized(anchors[i][1]['text']) for i in ids):
                raise ValueError('Quote must be a single-line exact excerpt from a bound fragment')
            if item.get('role') not in {'reported_fact','author_inference','context'}:raise ValueError('Invalid source role')
            files=[anchors[i][0] for i in ids]
            for file in files:require(run,file.get('channel','local'),Path(file['root'])/file['source_path'])
        if item['id'].startswith('EVID-'):
            if not re.fullmatch(r'EVID-\d+',item['id']) or not inventory:raise ValueError('EVID source requires inventory metadata')
            if not all(inventory.get(k) for k in ['observation','relevance','relevance_reason','source_origin','evidence_status']):
                raise ValueError('EVID requires observation, relevance, relevance_reason, source_origin, evidence_status')
            if inventory['source_origin'] not in {'customer_record','provider_record','external','synthetic'} or inventory['evidence_status'] not in {'observed','reported','assumed','synthetic'}:
                raise ValueError('Invalid inventory origin/status')
            if item['kind']=='simulation' and (inventory['source_origin']!='synthetic' or inventory['evidence_status']!='synthetic'):
                raise ValueError('Simulation inventory must remain synthetic')
    else:
        if item.get('kind') not in {'fact','inference','gap','proposal'} or item.get('basis') not in {'observed','derived','missing_evidence','simulation'}:
            raise ValueError('Invalid claim kind/basis; partial_evidence is not a basis')
        if item.get('status') not in {'supported','conditional','unknown','contradicted'} or not item.get('rationale'):
            raise ValueError('Claim requires status and rationale')
        refs=item.get('evidence_ids',[])
        sources={s['id']:s for s in ledger['sources']}
        if any(s not in sources for s in refs):raise ValueError('Register cited sources first')
        expected=len({sources[s]['independence_group'] for s in refs if sources[s]['kind']!='simulation'})
        if item.get('independent_sources')!=expected:raise ValueError('independent_sources must count original source groups')
        from grounded_audit import target_text,numeric_status_target
        if not item.get('targets'):raise ValueError('Claim requires substantive output target quotes')
        for target in item['targets']:
            if numeric_status_target(target_text(run,target)):raise ValueError('A contour status is not a claim target')
    key='sources' if kind=='source' else 'claims'
    if any(x['id']==item['id'] for x in ledger[key]):raise ValueError('ID already registered; review dependent claims before editing it')
    if kind=='source' and item['id'].startswith('EVID-'):
        path=output/'evidence_inventory.md'
        text=path.read_text(encoding='utf-8-sig') if path.exists() else '# Evidence Inventory\n'
        if re.search(r'^#{2,3}\s+'+re.escape(item['id'])+r'\b',text,re.M):raise ValueError('EVID already exists in inventory')
        fields=dict(source_path=files[0]['source_path'] if files else 'synthetic',source_kind=Path(files[0]['source_path']).suffix.lstrip('.') if files else 'synthetic',
                    evidence_type='quote' if files else 'observation',**inventory,retrieved_by='source_snapshot.py',
                    anchor_ids=json.dumps(item.get('anchor_ids',[])),source_quote=item.get('quote','simulation'))
        block='\n### '+item['id']+'\n'+'\n'.join('- '+k+': '+str(v) for k,v in fields.items())+'\n'
        atomic(path,text+block)
    ledger[key].append(item)
    if commit:atomic(output/'claim_ledger.json',json.dumps(ledger,ensure_ascii=False,indent=2))
    return item


def put(run,kind,record):
    with lock(output_dir(run)):
        return _put(run,kind,record)


@timed('claim_registration_batch')
def put_claims(run,records):
    """Validate a whole claim batch against real sources/targets, then commit once."""
    if not isinstance(records,list) or not records or len(records)>500 or any(not isinstance(r,dict) for r in records):
        raise ValueError('Expected 1–500 claim objects')
    output=output_dir(run)
    path=output/'claim_ledger.json'
    if path.is_symlink():raise ValueError('Claim ledger must not be a symlink')
    with lock(output):
        ledger=json.loads(path.read_text(encoding='utf-8-sig'))
        accepted=[_put(run,'claim',record,ledger=ledger,commit=False) for record in records]
        atomic(path,json.dumps(ledger,ensure_ascii=False,indent=2))
    return accepted


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('action',choices=['init','source','claim','batch-claims'])
    parser.add_argument('--run-dir',type=Path,required=True)
    parser.add_argument('--record',type=Path,help='UTF-8 JSON record; never executed')
    args=parser.parse_args()
    try:
        if args.action=='init':initialize(args.run_dir)
        else:
            if not args.record:parser.error('--record required')
            payload=json.loads(args.record.read_text(encoding='utf-8-sig'))
            accepted=put_claims(args.run_dir,payload) if args.action=='batch-claims' else [put(args.run_dir,args.action,payload)]
            print(json.dumps({'status':'ok','registered_ids':[r['id'] for r in accepted]},ensure_ascii=False))
    except (OSError,ValueError,KeyError,TypeError) as exc:parser.error(str(exc))

if __name__ == '__main__':
    from runtime_metrics import execute
    raise SystemExit(execute(main, 'audit_records', _HST_STARTED, _HST_CPU_STARTED))
